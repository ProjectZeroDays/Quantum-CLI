#!/usr/bin/env python3
"""Bash Bunny v2 / AI-driven duckie script generator.
Manual GUI buttons + input form to build exploit workflow and generate Ducky script payloads.
Requires Bash Bunny v2 and Android device with ADB access."""

class BashBunnyPayloadGenerator:
    """Generates Ducky scripts from manual GUI input forms."""
    
    def __init__(self, payload_type="default"):
        self.payload_type = payload_type
        self.steps = []
        self.commands = []
        
    def add_step(self, command_type, text):
        """Add a step to the payload."""
        if command_type == "STRING":
            self.steps.append(f"STRING {text}")
        elif command_type == "DELAY":
            self.steps.append(f"DELAY {text}")
        elif command_type == "KEY":
            self.steps.append(f"KEY {text}")
        elif command_type == "ENTER":
            self.steps.append("ENTER")
        elif command_type == "SWIPE":
            self.steps.append(f"SWIPE {text}")
        elif command_type == "REPEAT":
            self.steps.append(f"REPEAT {text}")
        else:
            self.steps.append(command_type)
    
    def generate_ducky_script(self):
        """Generate the final Ducky script."""
        script = []
        script.append("# Generated by Quantum CLI HID Payload Generator")
        script.append("# Auto-generated from GUI workflow")
        script.append("")
        for step in self.steps:
            script.append(step)
        return script

    def generate_from_prompt(self, prompt):
        """Generate payload from natural language prompt."""
        # Very basic parsing - real implementation would parse intent
        if "click" in prompt.lower():
            self.add_step("STRING click", "GUI")
            self.add_step("KEY space", " ")
            self.add_step("ENTER")
        elif "type" in prompt.lower():
            self.add_step("STRING", prompt.split("type")[1].strip())
            self.add_step("ENTER")
        elif "open" in prompt.lower():
            self.add_step("STRING", "open app")
            self.add_step("ENTER")
        elif "type password" in prompt.lower():
            self.add_step("STRING", "password")
            self.add_step("ENTER")
        # Default fallback
        if not self.steps:
            self.add_step("STRING default payload", "auto-generated")
        return self.build_ducky_script()

    def save_to_file(self, path="payload.ducky"):
        script = self.build_ducky_script()
        with open(path, "w") as f:
            f.write(script)
        return path